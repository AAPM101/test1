#!/usr/bin/env python3
"""Skill helper.

  skills.py new <name> --tool T
  skills.py bump <name> --tool T --note "what changed"
  skills.py registry          # rebuild registry.yaml
"""
import argparse
import re

from common import SKILLS, append, die, get_field, read, set_field, today, write


def frontmatter_get(text, key):
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    return get_field(m.group(1), key) if m else None


def frontmatter_set(text, key, value):
    m = re.match(r"(---\n)(.*?)(\n---)", text, re.S)
    if not m:
        die("SKILL.md has no frontmatter")
    return m.group(1) + set_field(m.group(2), key, value).rstrip("\n") + m.group(3) + text[m.end():]


def rebuild_registry():
    rows = []
    for d in sorted(SKILLS.iterdir()):
        f = d / "SKILL.md"
        if d.is_dir() and not d.name.startswith("_") and f.exists():
            t = read(f)
            rows.append(f"  - {{name: {d.name}, version: {frontmatter_get(t, 'version')}, "
                        f"updated_by: {frontmatter_get(t, 'updated_by')}, "
                        f"updated_at: {frontmatter_get(t, 'updated_at')}}}")
    write(SKILLS / "registry.yaml",
          "# Generated by build/skills.py. Do not edit by hand.\n" + ("skills:\n" + "\n".join(rows) if rows else "skills: []") + "\n")


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    for n in ("new", "bump"):
        s = sp.add_parser(n)
        s.add_argument("name")
        s.add_argument("--tool", required=True)
        if n == "bump":
            s.add_argument("--note", required=True)
    sp.add_parser("registry")
    a = ap.parse_args()

    if a.cmd == "registry":
        rebuild_registry()
        return
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", a.name):
        die("skill name: lowercase letters, digits, hyphens")
    d = SKILLS / a.name
    if a.cmd == "new":
        if d.exists():
            die(f"{d} exists")
        t = read(SKILLS / "_template" / "SKILL.md")
        for k, v in {"name": a.name, "created_by": a.tool, "created_at": today(),
                     "updated_by": a.tool, "updated_at": today()}.items():
            t = frontmatter_set(t, k, v)
        t = t.replace("# skill-name", f"# {a.name}")
        write(d / "SKILL.md", t)
        write(d / "CHANGELOG.md", f"# Changelog — {a.name}\n\n{today()} | {a.tool} | created | v1\n")
    else:
        f = d / "SKILL.md"
        if not f.exists():
            die(f"skill '{a.name}' not found")
        t = read(f)
        v = int(frontmatter_get(t, "version") or 1) + 1
        t = frontmatter_set(t, "version", str(v))
        t = frontmatter_set(t, "updated_by", a.tool)
        t = frontmatter_set(t, "updated_at", today())
        write(f, t)
        append(d / "CHANGELOG.md", f"{today()} | {a.tool} | {a.note} | v{v}\n")
    rebuild_registry()
    print("ok")


if __name__ == "__main__":
    main()
